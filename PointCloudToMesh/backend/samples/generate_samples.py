"""
Sample Point Cloud Generator
Generates clean, synthetic PLY point clouds (sphere, torus, spiral) for immediate testing.
Writes standard PLY files with coordinates, normals, and RGB colors.
"""
import math
from pathlib import Path
from typing import List, Tuple
from backend.config import SAMPLES_DIR


def write_ply_points(
    file_path: Path,
    points: List[Tuple[float, float, float]],
    normals: List[Tuple[float, float, float]],
    colors: List[Tuple[int, int, int]]
) -> None:
    """
    Writes point cloud data in standard ASCII PLY format.
    Compatible with Three.js PLYLoader, Open3D, MeshLab, and CloudCompare.
    """
    file_path.parent.mkdir(parents=True, exist_ok=True)
    num_points = len(points)

    with open(file_path, "w", encoding="ascii") as f:
        f.write("ply\n")
        f.write("format ascii 1.0\n")
        f.write(f"comment Generated by PointCloudToMesh Sample Generator\n")
        f.write(f"element vertex {num_points}\n")
        f.write("property float x\n")
        f.write("property float y\n")
        f.write("property float z\n")
        f.write("property float nx\n")
        f.write("property float ny\n")
        f.write("property float nz\n")
        f.write("property uchar red\n")
        f.write("property uchar green\n")
        f.write("property uchar blue\n")
        f.write("end_header\n")

        for (x, y, z), (nx, ny, nz), (r, g, b) in zip(points, normals, colors):
            f.write(
                f"{x:.5f} {y:.5f} {z:.5f} "
                f"{nx:.5f} {ny:.5f} {nz:.5f} "
                f"{int(r)} {int(g)} {int(b)}\n"
            )


def generate_sphere_ply(output_path: Path, num_points: int = 8000, radius: float = 1.0) -> Path:
    """
    Generates a sphere point cloud using Fibonacci lattice sampling for uniform distribution.
    """
    points = []
    normals = []
    colors = []

    golden_ratio = (1 + math.sqrt(5)) / 2
    phi = 2 * math.pi * golden_ratio

    for i in range(num_points):
        y = 1 - (i / float(num_points - 1)) * 2  # y goes from 1 to -1
        radius_at_y = math.sqrt(max(0.0, 1 - y * y))
        theta = phi * i

        x = math.cos(theta) * radius_at_y
        z = math.sin(theta) * radius_at_y

        px, py, pz = x * radius, y * radius, z * radius
        nx, ny, nz = x, y, z

        # Color gradient based on normal directions
        r = int(min(255, max(0, (nx * 0.5 + 0.5) * 255)))
        g = int(min(255, max(0, (ny * 0.5 + 0.5) * 255)))
        b = int(min(255, max(0, (nz * 0.5 + 0.5) * 255)))

        points.append((px, py, pz))
        normals.append((nx, ny, nz))
        colors.append((r, g, b))

    write_ply_points(output_path, points, normals, colors)
    return output_path


def generate_torus_ply(
    output_path: Path,
    num_u: int = 100,
    num_v: int = 80,
    r_major: float = 1.0,
    r_minor: float = 0.35
) -> Path:
    """
    Generates a torus point cloud with parametric ring coordinates and vibrant HSV colors.
    """
    points = []
    normals = []
    colors = []

    for i in range(num_u):
        u = (i / num_u) * 2 * math.pi
        cos_u = math.cos(u)
        sin_u = math.sin(u)

        for j in range(num_v):
            v = (j / num_v) * 2 * math.pi
            cos_v = math.cos(v)
            sin_v = math.sin(v)

            # Torus coordinates
            x = (r_major + r_minor * cos_v) * cos_u
            y = (r_major + r_minor * cos_v) * sin_u
            z = r_minor * sin_v

            # Surface normal
            nx = cos_v * cos_u
            ny = cos_v * sin_u
            nz = sin_v

            # Rainbow color across torus angles
            hue = (u / (2 * math.pi))
            r = int((math.sin(u) * 0.5 + 0.5) * 255)
            g = int((math.cos(v) * 0.5 + 0.5) * 255)
            b = int((math.sin(u + v) * 0.5 + 0.5) * 255)

            points.append((x, y, z))
            normals.append((nx, ny, nz))
            colors.append((r, g, b))

    write_ply_points(output_path, points, normals, colors)
    return output_path


def generate_all_samples() -> List[Path]:
    """Generates all default sample point clouds if they don't already exist."""
    sphere_path = SAMPLES_DIR / "sample_sphere.ply"
    torus_path = SAMPLES_DIR / "sample_torus.ply"

    created = []
    if not sphere_path.exists():
        generate_sphere_ply(sphere_path, num_points=6000, radius=1.0)
        created.append(sphere_path)

    if not torus_path.exists():
        generate_torus_ply(torus_path, num_u=80, num_v=60, r_major=1.0, r_minor=0.35)
        created.append(torus_path)

    return created


if __name__ == "__main__":
    generated = generate_all_samples()
    print(f"Generated {len(generated)} sample PLY files in {SAMPLES_DIR}")
